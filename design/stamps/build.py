"""Builds the station stamps from glyphs.py.

Writes public/stamps/<station-id>.svg (Gold, standalone) and
src/features/passport/station-art.ts (the same art, which the Stamp component
recolors per tier). Run from the repo root: python3 design/stamps/build.py
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from glyphs import STATIONS
from render import stamp, SCALLOP

ROOT = os.path.dirname(os.path.dirname(HERE))
os.makedirs(os.path.join(ROOT, "public/stamps"), exist_ok=True)
for sid, top, ribbon, lines, scene in STATIONS:
    svg = stamp(sid, top, ribbon, lines, scene, tier="gold", size=256, uid=sid.replace("place-", ""))
    svg = svg.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
    with open(os.path.join(ROOT, f"public/stamps/{sid}.svg"), "w") as f:
        f.write(svg + "\n")

art = {sid: {"top": top, "ribbon": ribbon, "lines": lines, "scene": [[r, d] for r, d in scene]}
       for sid, top, ribbon, lines, scene in STATIONS}
ts = [
    "// Generated by design/stamps/build.py from design/stamps/glyphs.py. Do not edit by hand.",
    "// One illustrated stamp per station with quests. Scene paths are drawn in a 100 x 100 box.",
    "",
    'export type ArtRole = "ink" | "tint" | "bg" | "line" | "bgline" | "accent";',
    "",
    "export interface StationArt {",
    "  /** Neighborhood or landmark area, on the top arc. */",
    "  top: string;",
    "  /** Station name, on the ribbon. */",
    "  ribbon: string;",
    "  /** T line badges: R, O, G, B. */",
    "  lines: string[];",
    "  scene: [ArtRole, string][];",
    "}",
    "",
    f"export const SCALLOP = {json.dumps(SCALLOP)};",
    "",
    f"export const STATION_ART: Record<string, StationArt> = {json.dumps(art, indent=2)};",
    "",
]
with open(os.path.join(ROOT, "src/features/passport/station-art.ts"), "w") as f:
    f.write("\n".join(ts))
print("built", len(STATIONS), "stamps")
