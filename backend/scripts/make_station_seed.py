def load_env_file():
    path = os.path.join(ROOT, ".env.local")
    if not os.path.exists(path):
        return
    for line in open(path):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


def fetch(route):
    url = f"https://api-v3.mbta.com/stops?filter[route]={route}&fields[stop]=name,latitude,longitude,municipality,address"
    req = urllib.request.Request(url)
    key = os.environ.get("MBTA_API_KEY")
    if key:
        req.add_header("x-api-key", key)
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.load(r)["data"]


def neighborhood(attrs):
    m = re.search(r"\b(0\d{4})\b", attrs.get("address") or "")
    if m and m.group(1) in ZIP_HOOD:
        return ZIP_HOOD[m.group(1)]
    return attrs.get("municipality") or "Boston"


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def render(stations):
    values = ",\n".join(
        f"  ({q(sid)}, {q(s['name'])}, array[{', '.join(q(l) for l in s['lines'])}], "
        f"{s['lat']}, {s['lon']}, {q(s['hood'])})"
        for sid, s in sorted(stations.items()))
    fixes = ",\n".join(
        f"  ({q(sid)}, {q(s['auto'])}, {q(s['hood'])})"
        for sid, s in sorted(stations.items()) if s["hood"] != s["auto"])
    sql = f"""-- Generated by backend/scripts/make_station_seed.py. Safe to re-run.
-- Updates name, lines and location; keeps neighborhood and story if already set.
insert into public.stations (id, name, lines, lat, lon, neighborhood) values
{values}
on conflict (id) do update set
  name = excluded.name, lines = excluded.lines, lat = excluded.lat, lon = excluded.lon;
"""
    if fixes:
        sql += f"""
-- Hand-fixed neighborhoods. Only replaces the automatic guess, never a name Suki typed.
update public.stations s set neighborhood = v.fixed
from (values
{fixes}
) as v(id, auto_guess, fixed)
where s.id = v.id and s.neighborhood = v.auto_guess;
"""
    return sql


def main():
    load_env_file()
    stations = {}
    # --from-file data.json lets you test without the network: {"Red": [...], ...}
    fixture = json.load(open(sys.argv[2])) if len(sys.argv) > 2 and sys.argv[1] == "--from-file" else None
    for route in ROUTES:
        rows = fixture[route] if fixture else fetch(route)
        for s in rows:
            a = s["attributes"]
            st = stations.setdefault(s["id"], {
                "name": a["name"], "lat": a["latitude"], "lon": a["longitude"],
                "auto": neighborhood(a), "hood": OVERRIDES.get(s["id"], neighborhood(a)), "lines": []})
            if route not in st["lines"]:
                st["lines"].append(route)
        print(f"{route}: {len(rows)} stations")

    open(OUT, "w").write(render(stations))
    hoods = {}
    for s in stations.values():
        hoods[s["hood"]] = hoods.get(s["hood"], 0) + 1
    print(f"\n{len(stations)} stations written to {os.path.relpath(OUT, ROOT)}")
    print("By neighborhood:", ", ".join(f"{h} {n}" for h, n in sorted(hoods.items())))


if __name__ == "__main__":
    main()
