#!/usr/bin/env python3
"""Build backend/supabase/seed_stations.sql from the MBTA API.

Run from the repo root:   python3 backend/scripts/make_station_seed.py
Then paste the SQL file into Supabase > SQL Editor > New query > Run.

Loads every Red, Orange and Green Line station (parent stop ids like place-kencl)
with its lines, location and a neighborhood guessed from the ZIP code.
Re-running is safe: it updates name, lines and location, and keeps any
neighborhood or story Suki has already edited in Supabase.
Uses only the Python standard library.
"""
import json
import os
import re
import sys
import urllib.request

ROUTES = ["Red", "Orange", "Green-B", "Green-C", "Green-D", "Green-E"]
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "backend", "supabase", "seed_stations.sql")

# ZIP -> neighborhood. Anything not listed falls back to the town name (Somerville, Quincy...).
