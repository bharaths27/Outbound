#!/usr/bin/env node
// Builds src/lib/data/mock/content.ts from content/stations.csv and content/quests.csv,
// so the mock data service shows Suki's real stations and quests.
//
//   npm run content
//
// Validation of the values (types, hours format, station ids) lives in
// src/lib/data/mock/content.test.ts, which `npm test` runs. Standard library only.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src/lib/data/mock/content.ts");

/** RFC 4180 CSV: quoted fields, "" escapes, commas and newlines inside quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  text = text.replace(/^﻿/, "");
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        quoted = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  const [header, ...body] = rows.filter((r) => r.some((v) => v.trim() !== ""));
  return body.map((r, n) => {
    if (r.length !== header.length) throw new Error(`row ${n + 2}: ${r.length} fields, expected ${header.length}`);
    return Object.fromEntries(header.map((h, i) => [h.trim(), r[i].trim()]));
  });
}

const read = (name) => parseCsv(readFileSync(join(ROOT, "content", name), "utf8"));
const list = (v) => (v ? v.split("|").map((s) => s.trim()).filter(Boolean) : []);
const num = (v, field, id) => {
  const n = Number(v);
  if (v === "" || Number.isNaN(n)) throw new Error(`${id}: ${field} "${v}" is not a number`);
  return n;
};

const stations = read("stations.csv").map((s) => ({
  id: s.id,
  name: s.name,
  lines: list(s.lines),
  lat: num(s.lat, "lat", s.id),
  lon: num(s.lon, "lon", s.id),
  neighborhood: s.neighborhood,
  story: s.story || null,
}));

const quests = read("quests.csv").map((q) => ({
  id: q.id,
  station_id: q.station_id,
  type: q.type,
  title: q.title,
  description: q.description || null,
  lat: num(q.lat, "lat", q.id),
  lon: num(q.lon, "lon", q.id),
  price_tier: num(q.price_tier, "price_tier", q.id),
  vibe_tags: list(q.vibe_tags),
  hours: q.hours || null,
  photo_url: q.photo_url || null,
  xp: num(q.xp, "xp", q.id),
  // Optional columns; schema defaults when the CSV leaves them out.
  checkin_radius_m: q.checkin_radius_m ? num(q.checkin_radius_m, "checkin_radius_m", q.id) : 75,
  // QR codes are secrets that only check_in() reads; content only says a quest needs one.
  requires_qr: Boolean(q.qr_code),
  duration_min: num(q.duration_min, "duration_min", q.id),
  walk_min: num(q.walk_min, "walk_min", q.id),
}));

const json = (v) => JSON.stringify(v, null, 2);
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-content.mjs from content/*.csv. Do not edit by hand:
// change the CSVs, then run \`npm run content\`.

import type { Quest, Station } from "@/lib/types";

export const stations: Station[] = ${json(stations)};

export const quests: Quest[] = ${json(quests)} as Quest[];
`,
);
console.log(`Wrote ${stations.length} stations and ${quests.length} quests to src/lib/data/mock/content.ts`);

// ---------- content/seed.sql: the same content for Supabase ----------
// Safe to re-run. Upserts only: it never deletes, because deleting a quest also deletes
// its visits (on delete cascade), including the seeded players' leaderboard history.

const sql = (v) => {
  if (v === null || v === undefined || v === "") return "null";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const sqlArray = (items) => (items.length ? `array[${items.map(sql).join(", ")}]::text[]` : "'{}'::text[]");
const rawQuests = read("quests.csv");
const hasQrColumn = rawQuests.some((q) => "qr_code" in q);

const stationRows = stations.map(
  (s) =>
    `  (${[sql(s.id), sql(s.name), sqlArray(s.lines), sql(s.lat), sql(s.lon), sql(s.neighborhood), sql(s.story)].join(", ")})`,
);
const questCols = [
  "id", "station_id", "type", "title", "description", "lat", "lon", "price_tier", "vibe_tags",
  "hours", "photo_url", "xp", "checkin_radius_m", "duration_min", "walk_min", ...(hasQrColumn ? ["qr_code"] : []),
];
const questRows = quests.map((q, i) => {
  const values = [
    sql(q.id), sql(q.station_id), sql(q.type), sql(q.title), sql(q.description), sql(q.lat), sql(q.lon),
    sql(q.price_tier), sqlArray(q.vibe_tags), sql(q.hours), sql(q.photo_url), sql(q.xp), sql(q.checkin_radius_m),
    sql(q.duration_min), sql(q.walk_min), ...(hasQrColumn ? [sql(rawQuests[i].qr_code)] : []),
  ];
  return `  (${values.join(", ")})`;
});
const updateCols = questCols.filter((c) => c !== "id");

const SQL_OUT = join(ROOT, "content", "seed.sql");
writeFileSync(
  SQL_OUT,
  `-- GENERATED by scripts/build-content.mjs from content/*.csv (npm run content). Do not edit.
-- Suki's stations and quests for Supabase. Run AFTER schema.sql, migrations 002-004, and
-- seed_stations.sql: Supabase > SQL Editor > New query > paste > Run.
--
-- Safe to re-run. It adds or updates rows and never deletes anything:
--   - stations: sets neighborhood and story (inserts the station if it's missing)
--   - quests: inserts new ones, updates existing ones with the same id${hasQrColumn ? "" : "\n--     (qr_code is left as it is; the CSV has no qr_code column)"}
-- Bharath's starter quests (seed_quests_starter.sql) stay. See the end of this file to remove them.

begin;

insert into public.stations (id, name, lines, lat, lon, neighborhood, story) values
${stationRows.join(",\n")}
on conflict (id) do update set neighborhood = excluded.neighborhood, story = excluded.story;

insert into public.quests (${questCols.join(", ")}) values
${questRows.join(",\n")}
on conflict (id) do update set
  ${updateCols.map((c) => `${c} = excluded.${c}`).join(",\n  ")};

commit;

-- Optional: remove starter quests that aren't in Suki's content, keeping the expo QR quest.
-- WARNING: deleting a quest deletes its visits (on delete cascade), which wipes the seeded
-- players' leaderboard history. Re-run \`node scripts/seed-demo.mjs\` afterward to rebuild it.
--
-- delete from public.quests
-- where id not in (${quests.map((q) => sql(q.id)).join(", ")}, 'bu-gsu-expo');
`,
);
console.log(`Wrote ${stations.length} stations and ${quests.length} quests to content/seed.sql`);
